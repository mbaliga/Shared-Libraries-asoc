// Regenerates ../schemas.js from ../schemas/*.json so the browser needs no fetch. Run: node tools/embed-schemas.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rd = (p) => JSON.parse(readFileSync(join(root, 'schemas', p), 'utf8'));
const out = `/* GENERATED by tools/embed-schemas.mjs from schemas/*.json — do not edit. See schemas/SOURCE.md for provenance. */
export const loopDefinitionSchema = ${JSON.stringify(rd('loop-definition.v2.schema.json'))};
export const loopRunSchema = ${JSON.stringify(rd('loop-run.schema.json'))};
export const validationRules = ${JSON.stringify(rd('registries/loop-validation-rules.v1.json'))};
export const semanticDigestRegistry = ${JSON.stringify(rd('registries/semantic-digest.v1.json'))};
`;
writeFileSync(join(root, 'schemas.js'), out);
console.log('wrote schemas.js', out.length, 'bytes');
